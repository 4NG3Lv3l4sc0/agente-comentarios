# =========================================================
# VALIDACIÓN
# =========================================================

def validate_templates():

    # =====================================================
    # VALIDAR PLANTILLAS GENERALES
    # =====================================================

    ids = set()

    for template in COMMENT_TEMPLATES:

        template_id = template["id"]
        text = template["text"]

        if template_id in ids:
            raise ValueError(
                f"ID de plantilla duplicado: {template_id}"
            )

        ids.add(template_id)

        if "{uid}" not in text:
            raise ValueError(
                f"La plantilla {template_id} "
                "no contiene {{uid}}"
            )

        if "{server}" not in text:
            raise ValueError(
                f"La plantilla {template_id} "
                "no contiene {{server}}"
            )


    # =====================================================
    # VALIDAR PLANTILLAS CONTEXTUALES
    # =====================================================

    contextual_ids = set()

    for topic, data in CONTEXTUAL_TEMPLATES.items():

        # -------------------------------------------------
        # Validar palabras clave
        # -------------------------------------------------

        if not data["keywords"]:
            raise ValueError(
                f"El tema {topic} no tiene keywords"
            )

        # -------------------------------------------------
        # Validar plantillas
        # -------------------------------------------------

        if not data["templates"]:
            raise ValueError(
                f"El tema {topic} no tiene plantillas"
            )

        # -------------------------------------------------
        # Revisar cada plantilla contextual
        # -------------------------------------------------

        for template in data["templates"]:

            template_id = template["id"]
            text = template["text"]

            # Evitar IDs contextuales duplicados

            if template_id in contextual_ids:
                raise ValueError(
                    f"ID contextual duplicado: "
                    f"{template_id}"
                )

            # Evitar coincidencias con IDs generales

            if template_id in ids:
                raise ValueError(
                    f"El ID {template_id} "
                    "también existe en las "
                    "plantillas generales"
                )

            contextual_ids.add(template_id)

            # UID obligatorio

            if "{uid}" not in text:
                raise ValueError(
                    f"La plantilla contextual "
                    f"{template_id} "
                    "no contiene {{uid}}"
                )

            # Servidor obligatorio

            if "{server}" not in text:
                raise ValueError(
                    f"La plantilla contextual "
                    f"{template_id} "
                    "no contiene {{server}}"
                )


    # =====================================================
    # VALIDACIÓN CORRECTA
    # =====================================================

    return True


